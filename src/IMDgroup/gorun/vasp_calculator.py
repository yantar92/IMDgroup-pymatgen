"""ASE ``Vasp`` calculator variant used by gorun's ``INCAR.py`` wrapper."""

from __future__ import annotations

from ase.calculators.vasp import Vasp


class IMDASEVasp(Vasp):
    """ASE ``Vasp`` calculator that does not own POTCAR generation.

    ``gorun`` generates POTCAR through pymatgen in ``prepare_inputs``,
    so this calculator must not read ``VASP_PP_PATH`` or write POTCAR
    again.  Overrides:

    - ``_build_pp_list`` returns an empty list so ``initialize`` never
      resolves pseudopotential paths.
    - ``write_potcar`` is a no-op.
    - ``default_nelect_from_ppp`` raises: it derives NELECT from the
      POTCAR valence counts, which gorun does not track.
    """

    def _build_pp_list(self, atoms, setups=None, special_setups=()):
        """Return an empty pseudopotential path list.

        POTCAR is generated by gorun through pymatgen, so the ASE
        calculator must not resolve or read pseudopotentials from
        ``VASP_PP_PATH``.
        """
        return []

    def write_potcar(self, suffix="", directory="./") -> None:
        """No-op: gorun has already written POTCAR."""
        return None

    def default_nelect_from_ppp(self) -> float:
        """Unsupported: derived from POTCAR valence counts.

        Raise instead of returning a wrong value.  Set ``NELECT`` in
        INCAR directly, or file a bug report to add support for the
        ASE ``charge`` parameter.
        """
        raise NotImplementedError(
            "IMDASEVasp cannot derive NELECT from the 'charge' parameter "
            "because it does not track pseudopotential valence counts.  "
            "Set NELECT in INCAR instead, or file a bug report at "
            "https://github.com/yantar92/IMDgroup-pymatgen/issues "
            "to request support."
        )
